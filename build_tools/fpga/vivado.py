"""Generate Vivado build and programming scripts for FPGA examples."""

import re
import shlex
import subprocess
from pathlib import Path

import build_tools.common.library_dependency
import build_tools.common


def build_with_vivado(tcl_path: Path) -> None:
    script = tcl_path.resolve(strict=True)
    subprocess.run(
        ["vivado", "-mode", "batch", "-source", str(script)],
        cwd=script.parent,
        check=True,
    )


def program_with_vivado(tcl_path: Path) -> None:
    script = tcl_path.resolve(strict=True)
    command = ["vivado", "-mode", "batch", "-source", str(script)]
    print(shlex.join(command), flush=True)
    subprocess.run(
        command,
        cwd=script.parent,
        check=True,
    )


class ProgramTclGenerator:
    """Generate a JTAG programming script for an existing bitstream."""

    def __init__(self, *, device_name: str, top_name: str) -> None:
        self._device_name = device_name
        self._top_name = top_name

    def generate(self, build_dir: Path) -> Path:
        build_dir = build_dir.resolve()
        device_name = self._device_name

        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", self._top_name):
            raise ValueError(f"top_name must name a Verilog module: {self._top_name}")
        bitstream = build_dir / f"{self._top_name}.bit"
        if not bitstream.is_file():
            raise FileNotFoundError(f"Missing bitstream: {bitstream}. Build the FPGA example before programming")

        commands = [
            "# AUTOGENERATED by ProgramTclGenerator. DO NOT EDIT.",
            "open_hw_manager",
            "connect_hw_server",
            "open_hw_target",
            f"set device [get_hw_devices {BuildTclGenerator._tcl_quote(device_name)}]",
            "current_hw_device $device",
            f"set_property PROGRAM.FILE {BuildTclGenerator._tcl_quote(str(bitstream))} $device",
            "program_hw_devices $device",
            "close_hw_target",
            "disconnect_hw_server",
            "close_hw_manager",
        ]
        build_dir.mkdir(parents=True, exist_ok=True)
        output = build_dir / "program.tcl"
        output.write_text("\n".join(commands) + "\n")
        return output


class BuildTclGenerator:
    """Read library dependencies, then explicit absolute RTL paths in supplied order."""

    def __init__(
        self,
        *,
        part: str,
        top_name: str,
        constraints_file: Path,
        libraries: list[build_tools.common.library_dependency.LibraryDependency],
        rtl_files: list[Path],
    ) -> None:
        self._part = part
        self._top_name = top_name
        self._constraints_file = constraints_file
        self._libraries = list(libraries)
        self._rtl_files = list(rtl_files)
        for path in [self._constraints_file, *self._rtl_files]:
            if not path.is_absolute():
                raise ValueError(f"RTL and constraint files must use absolute paths: {path}")

    def generate(self, build_dir: Path) -> Path:
        build_dir = build_dir.resolve()
        top = self._top_name
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_$]*", top):
            raise ValueError(f"top_name must name a Verilog module: {top}")
        constraints = self._constraints_file.resolve()
        if not constraints.is_file():
            raise ValueError(f"Missing constraints file: {constraints}")

        sources = [
            *(build_tools.common.REPO_ROOT / source for library in self._libraries for source in library.rtl_files()),
            *self._rtl_files,
        ]
        commands = [
            "# AUTOGENERATED by BuildTclGenerator. DO NOT EDIT.",
            f"file mkdir {self._tcl_quote(str(build_dir))}",
        ]
        # Preserve order: RTL packages must be read before modules that use them.
        # Resolve paths before deduplicating so aliases to the same file count once.
        for source in dict.fromkeys(source.resolve(strict=True) for source in sources):
            if not source.is_file():
                raise ValueError(f"RTL source is not a file: {source}")
            commands.append(f"read_verilog -sv {self._tcl_quote(str(source))}")

        bitstream = str(build_dir / f"{top}.bit")
        # Vivado expects -loadbit to be a Tcl list: direction, address, bitstream.
        loadbit = f"up 0x00000000 {self._tcl_quote(bitstream)}"
        commands.extend([
            f"read_xdc {self._tcl_quote(str(constraints))}",
            f"synth_design -top {self._tcl_quote(top)} -part {self._tcl_quote(self._part)}",
            "set_property CFGBVS VCCO [current_design]",
            "set_property CONFIG_VOLTAGE 3.3 [current_design]",
            "set_property BITSTREAM.CONFIG.SPI_BUSWIDTH 4 [current_design]",
            "set_property CONFIG_MODE SPIx4 [current_design]",
            "opt_design",
            "place_design",
            "phys_opt_design",
            "route_design",
            f"report_timing_summary -file {self._tcl_quote(str(build_dir / 'timing_summary.rpt'))}",
            f"report_utilization -file {self._tcl_quote(str(build_dir / 'utilization.rpt'))}",
            f"report_drc -file {self._tcl_quote(str(build_dir / 'drc.rpt'))}",
            f"write_checkpoint -force {self._tcl_quote(str(build_dir / f'{top}_routed.dcp'))}",
            f"write_bitstream -force {self._tcl_quote(bitstream)}",
            "write_cfgmem -force -format mcs -size 4 -interface SPIx4 "
            f"-loadbit {self._tcl_quote(loadbit)} -file {self._tcl_quote(str(build_dir / f'{top}.mcs'))}",
        ])

        build_dir.mkdir(parents=True, exist_ok=True)
        output = build_dir / "build.tcl"
        output.write_text("\n".join(commands) + "\n")
        return output

    @staticmethod
    def _tcl_quote(value: str) -> str:
        """Quote one Tcl string without expanding special characters in file paths."""
        escapes = {
            "\\": "\\\\",
            '"': '\\"',
            "$": "\\$",
            "[": "\\[",
            "]": "\\]",
            "\n": "\\n",
            "\r": "\\r",
            "\t": "\\t",
        }
        return '"' + "".join(escapes.get(char, char) for char in value) + '"'
